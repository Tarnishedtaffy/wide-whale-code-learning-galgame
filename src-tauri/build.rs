use std::collections::HashMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::time::{SystemTime, UNIX_EPOCH};

fn parse_dotenv_file(path: &Path) -> HashMap<String, String> {
    let mut map = HashMap::new();
    let Ok(raw) = fs::read_to_string(path) else {
        return map;
    };
    for line in raw.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        let Some((k, v)) = trimmed.split_once('=') else {
            continue;
        };
        let key = k.trim().to_string();
        let mut val = v.trim().to_string();
        if (val.starts_with('"') && val.ends_with('"') && val.len() >= 2)
            || (val.starts_with('\'') && val.ends_with('\'') && val.len() >= 2)
        {
            val = val[1..val.len() - 1].to_string();
        }
        map.insert(key, val);
    }
    map
}

fn splitmix64(state: &mut u64) -> u64 {
    *state = state.wrapping_add(0x9E37_79B9_7F4A_7C15);
    let mut z = *state;
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}

fn xor_bytes(data: &[u8], pad: &[u8; 32]) -> Vec<u8> {
    data.iter()
        .enumerate()
        .map(|(i, b)| b ^ pad[i % pad.len()])
        .collect()
}

fn format_byte_slice(bytes: &[u8]) -> String {
    if bytes.is_empty() {
        return "&[]".to_string();
    }
    let parts: Vec<String> = bytes.iter().map(|b| format!("0x{b:02X}")).collect();
    format!("&[{}]", parts.join(", "))
}

fn main() {
    println!("cargo:rerun-if-changed=../.env.local");
    println!("cargo:rerun-if-changed=.env.local");
    println!("cargo:rerun-if-env-changed=MNK_EMBED_AI_BASE_URL");
    println!("cargo:rerun-if-env-changed=MNK_EMBED_AI_API_KEY");
    println!("cargo:rerun-if-env-changed=MNK_EMBED_AI_MODEL");

    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".into()));
    let mut dotenv_vars = parse_dotenv_file(&manifest_dir.join("../.env.local"));
    for (k, v) in parse_dotenv_file(&manifest_dir.join(".env.local")) {
        dotenv_vars.insert(k, v);
    }

    let get_cfg = |key: &str| -> String {
        env::var(key)
            .ok()
            .filter(|s| !s.trim().is_empty())
            .or_else(|| dotenv_vars.get(key).cloned())
            .unwrap_or_default()
            .trim()
            .to_string()
    };

    let base_url = get_cfg("MNK_EMBED_AI_BASE_URL");
    let api_key = get_cfg("MNK_EMBED_AI_API_KEY");
    let model = get_cfg("MNK_EMBED_AI_MODEL");

    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_nanos() as u64)
        .unwrap_or(0xA5A5_5A5A_F0F0_0F0F);
    let mut seed = nanos ^ (std::process::id() as u64).rotate_left(17);
    let mut pad = [0u8; 32];
    for chunk in pad.chunks_exact_mut(8) {
        chunk.copy_from_slice(&splitmix64(&mut seed).to_le_bytes());
    }

    let enc_url = xor_bytes(base_url.as_bytes(), &pad);
    let enc_key = xor_bytes(api_key.as_bytes(), &pad);
    let enc_model = xor_bytes(model.as_bytes(), &pad);

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR must be set"));
    let generated = format!(
        "// Auto-generated by build.rs from optional untracked .env.local\n\
         const EMBED_PAD: &[u8] = {pad_lit};\n\
         const EMBED_URL_ENC: &[u8] = {url_lit};\n\
         const EMBED_KEY_ENC: &[u8] = {key_lit};\n\
         const EMBED_MODEL_ENC: &[u8] = {model_lit};\n",
        pad_lit = format_byte_slice(&pad),
        url_lit = format_byte_slice(&enc_url),
        key_lit = format_byte_slice(&enc_key),
        model_lit = format_byte_slice(&enc_model),
    );
    fs::write(out_dir.join("embedded_ai_defaults.rs"), generated)
        .expect("failed to write embedded_ai_defaults.rs");

    tauri_build::build()
}
